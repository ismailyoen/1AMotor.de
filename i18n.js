//  Sprach-Engine  v2
//  Neu:  data-i18n-html   → innerHTML statt textContent
//        data-i18n-title  → title-Attribut
//        data-i18n-alt    → alt-Attribut
//        data-i18n-aria   → aria-label-Attribut
//        I18n.t(key, {n:5})  → Platzhalter {n} ersetzen
//        I18n.term(name)     → DB-Begriffe (Kategorien, Zustände) übersetzen
//        I18n.price(n) / I18n.num(n) → länderrichtige Formatierung
//        Event "i18n:changed" → dynamische Skripte können neu rendern
// ══════════════════════════════════════════════════════════════════
const I18n = {
  lang: localStorage.getItem("1amotor_lang") || "de",

  locales: { de: "de-DE", en: "en-GB", fr: "fr-FR" },

  // ── Text nachschlagen ───────────────────────────────────────────
  t(key, vars) {
    let s = translations[this.lang]?.[key];
    if (s === undefined) s = translations["de"]?.[key];
    if (s === undefined) s = key;
    if (vars) {
      for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    }
    return s;
  },

  // ── Begriffe aus der Datenbank (immer deutsch gespeichert) ──────
  term(name) {
    if (!name) return name;
    if (this.lang === "de") return name;
    return dbTerms[this.lang]?.[name] || name;
  },

  locale() {
    return this.locales[this.lang] || "de-DE";
  },

  num(n) {
    return Number(n || 0).toLocaleString(this.locale());
  },

  price(n) {
    return Number(n || 0).toLocaleString(this.locale(), {
      style: "currency",
      currency: "EUR"
    });
  },

  setLang(lang) {
    this.lang = lang;
    localStorage.setItem("1amotor_lang", lang);
    this.apply();
    this.updateToggle();
  },

  // ── Übersetzungen auf das DOM anwenden ──────────────────────────
  apply() {
    // Reiner Text
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key  = el.getAttribute("data-i18n");
      const attr = el.getAttribute("data-i18n-attr");
      if (attr) el.setAttribute(attr, this.t(key));
      else      el.textContent = this.t(key);
    });

    // HTML-Inhalt (Texte mit Links, <br>, <span> …)
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      el.innerHTML = this.t(el.getAttribute("data-i18n-html"));
    });

    // Attribute
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      el.placeholder = this.t(el.getAttribute("data-i18n-placeholder"));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      el.title = this.t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(el => {
      el.alt = this.t(el.getAttribute("data-i18n-alt"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(el => {
      el.setAttribute("aria-label", this.t(el.getAttribute("data-i18n-aria")));
    });

    // Seitentitel & Meta-Description
    const tKey = document.documentElement.getAttribute("data-i18n-doctitle");
    if (tKey) document.title = this.t(tKey);
    const dKey = document.documentElement.getAttribute("data-i18n-docdesc");
    if (dKey) {
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute("content", this.t(dKey));
    }

    // <html lang="…">
    document.documentElement.lang = this.lang;

    // Dynamische Skripte informieren (index-live.js, suche-live.js …)
    window.dispatchEvent(new CustomEvent("i18n:changed", { detail: { lang: this.lang } }));
  },

  updateToggle() {
    const btn = document.getElementById("lang-toggle");
    if (!btn) return;
    const flags  = { de: "🇩🇪", en: "🇬🇧", fr: "🇫🇷" };
    const labels = { de: "DE",  en: "EN",  fr: "FR"  };
    btn.innerHTML = `${flags[this.lang]} ${labels[this.lang]} <span style="font-size:9px;opacity:.7;">▾</span>`;
  },

  injectToggle() {
    if (document.getElementById("lang-toggle")) return;

    const wrapper = document.createElement("div");
    wrapper.id = "lang-wrapper";
    wrapper.style.cssText = "position:relative;display:inline-block;";

    const btn = document.createElement("button");
    btn.id = "lang-toggle";
    btn.type = "button";
    btn.style.cssText = `
      border:1.5px solid #dbe3ea; background:#fff;
      border-radius:8px; padding:7px 11px; font-size:13px; font-weight:700;
      cursor:pointer; color:#334155; transition:all .15s;
      font-family:inherit; white-space:nowrap; display:flex;
      align-items:center; gap:5px;
    `;

    const dropdown = document.createElement("div");
    dropdown.id = "lang-dropdown";
    dropdown.style.cssText = `
      display:none; position:absolute; top:calc(100% + 6px); right:0;
      background:#fff; border:1px solid #dbe3ea; border-radius:12px;
      box-shadow:0 8px 24px rgba(13,27,42,0.12); min-width:130px;
      z-index:1000; overflow:hidden;
    `;

    const langs = [
      { code: "de", flag: "🇩🇪", label: "Deutsch"  },
      { code: "en", flag: "🇬🇧", label: "English"  },
      { code: "fr", flag: "🇫🇷", label: "Français" },
    ];

    langs.forEach(l => {
      const item = document.createElement("button");
      item.type = "button";
      item.style.cssText = `
        display:flex; align-items:center; gap:9px; width:100%;
        padding:11px 14px; border:none; background:none;
        font-size:14px; font-weight:600; color:#334155;
        cursor:pointer; text-align:left; font-family:inherit;
        transition:background .12s;
      `;
      item.innerHTML = `${l.flag} ${l.label}`;
      item.addEventListener("mouseenter", () => item.style.background = "#f0f4f8");
      item.addEventListener("mouseleave", () => item.style.background = "none");
      item.addEventListener("click", () => {
        this.setLang(l.code);
        dropdown.style.display = "none";
      });
      dropdown.appendChild(item);
    });

    btn.addEventListener("click", (e) => {
      e.stopPropagation();
      dropdown.style.display = dropdown.style.display === "none" ? "block" : "none";
    });
    document.addEventListener("click", () => { dropdown.style.display = "none"; });

    wrapper.appendChild(btn);
    wrapper.appendChild(dropdown);

    const target = [
      document.querySelector(".header-right"),
      document.querySelector(".header-actions"),
      document.querySelector(".hdr-right"),
    ].find(t => t !== null);

    if (target) target.insertBefore(wrapper, target.firstChild);

    this.updateToggle();
  },

  init() {
    // Sprache so früh wie möglich am <html>-Tag setzen
    document.documentElement.lang = this.lang;

    const start = () => {
      this.injectToggle();
      this.apply();
    };

    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", start);
    } else {
      start();
    }
  }
};

I18n.init();
